#!/usr/bin/env python3
"""Writes a tiny Game Boy test ROM (32 KB, our own code, no commercial content) for checking the emulator pipeline:
stripes of the four shades on the screen; the d-pad scrolls them. Usage: make-testrom.py out.gb"""
import sys

code = []
labels = {}
fix = []

def b(*x): code.extend(x)
def label(n): labels[n] = len(code)
def jr(op, n): code.append(op); fix.append((len(code), n)); code.append(0)

b(0xF3)                      # di
b(0x31, 0xFE, 0xFF)          # ld sp,$FFFE
label('w1'); b(0xF0, 0x44, 0xFE, 0x90); jr(0x38, 'w1')   # wait for vblank (LY >= 144)
b(0xAF, 0xE0, 0x40)          # LCD off
b(0x3E, 0xE4, 0xE0, 0x47)    # BGP
# tile 1 (colour 3), tile 2 (colour 1), tile 3 (colour 2) at $8010..$803F
b(0x21, 0x10, 0x80, 0x06, 0x10, 0x3E, 0xFF); label('l1'); b(0x22, 0x05); jr(0x20, 'l1')
b(0x06, 0x08); label('l2'); b(0x3E, 0xFF, 0x22, 0xAF, 0x22, 0x05); jr(0x20, 'l2')
b(0x06, 0x08); label('l3'); b(0xAF, 0x22, 0x3E, 0xFF, 0x22, 0x05); jr(0x20, 'l3')
# background map $9800..$9BFF: tile numbers 0,1,2,3 repeating
b(0x21, 0x00, 0x98, 0x01, 0x00, 0x04, 0x16, 0x00)
label('l4'); b(0x7A, 0xE6, 0x03, 0x22, 0x14, 0x0B, 0x78, 0xB1); jr(0x20, 'l4')
b(0x3E, 0x91, 0xE0, 0x40)    # LCD on, BG on, tiles at $8000
label('main')
label('w2'); b(0xF0, 0x44, 0xFE, 0x90); jr(0x20, 'w2')   # wait for LY == 144
b(0x3E, 0x20, 0xE0, 0x00, 0xF0, 0x00, 0xF0, 0x00, 0x2F, 0xE6, 0x0F, 0x47)   # b = d-pad pressed (bit0 R, 1 L, 2 U, 3 D)
b(0xCB, 0x40, 0x28, 0x05, 0xF0, 0x43, 0x3C, 0xE0, 0x43)  # right: SCX++
b(0xCB, 0x48, 0x28, 0x05, 0xF0, 0x43, 0x3D, 0xE0, 0x43)  # left: SCX--
b(0xCB, 0x50, 0x28, 0x05, 0xF0, 0x42, 0x3D, 0xE0, 0x42)  # up: SCY--
b(0xCB, 0x58, 0x28, 0x05, 0xF0, 0x42, 0x3C, 0xE0, 0x42)  # down: SCY++
label('w3'); b(0xF0, 0x44, 0xFE, 0x90); jr(0x28, 'w3')   # wait until LY leaves 144
b(0xC3, 0x50 + labels['main'], 0x01)                      # jp main

for pos, n in fix:
    off = labels[n] - (pos + 1)
    assert -128 <= off <= 127, n
    code[pos] = off & 0xFF

rom = bytearray(0x8000)
rom[0x100:0x104] = bytes([0x00, 0xC3, 0x50, 0x01])
rom[0x134:0x134 + 9] = b'DSGB TEST'
rom[0x147] = 0; rom[0x148] = 0; rom[0x149] = 0
x = 0
for i in range(0x134, 0x14D):
    x = (x - rom[i] - 1) & 0xFF
rom[0x14D] = x
rom[0x150:0x150 + len(code)] = bytes(code)
open(sys.argv[1], 'wb').write(rom)
print("wrote", sys.argv[1], len(code), "bytes of code")
