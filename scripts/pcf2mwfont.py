#!/usr/bin/env python3
"""Convert an X11 PCF bitmap font (gzip ok) into a Microwindows compiled-in font (MWCFONT, C source).
usage: pcf2mwfont.py <font.pcf[.gz]> <C name, e.g. X6x10> > X6x10.c
The X11 "misc-fixed" fonts are public domain. Characters 0..255 (ISO 8859-1), one 16 bit word per row."""
import gzip, sys
from PIL import PcfFontFile

path, name = sys.argv[1], sys.argv[2]
fp = gzip.open(path) if path.endswith('.gz') else open(path, 'rb')
f = PcfFontFile.PcfFontFile(fp)
w, h = f.glyph[ord('A')][3].size
asc = -f.glyph[ord('A')][1][1]
print('/* Generated by scripts/pcf2mwfont.py from %s (X11 misc-fixed, public domain) */' % path.split('/')[-1])
print('#include "device.h"\n')
print('static MWIMAGEBITS %s_bits[] = {' % name)
for c in range(256):
    g = f.glyph[c]
    im = g[3] if g else None
    for y in range(h):
        word = 0
        if im is not None and y < im.size[1]:
            for x in range(min(w, im.size[0])):
                if im.getpixel((x, y)):
                    word |= 0x8000 >> x
        print('0x%04x,' % word)
    print('/* %d */' % c)
print('};\n')
print('MWCFONT font_%s = {\n\t"%s",\n\t%d,\n\t%d,\n\t%d,\n\t0,\n\t256,\n\t%s_bits,\n\t0,\n\t0\n};' % (name, name, w, h, asc, name))
